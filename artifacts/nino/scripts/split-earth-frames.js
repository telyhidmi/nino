#!/usr/bin/env node
// Splits assets/earth/globe_t{0..8}.jpg (9x8 atlases, 72 frames, lon 0..355 step 5) into
// individual 128px frames at assets/earth/frames/t{T}_{NN}.jpg, and writes components/earthFrames.ts
// with a static require() map (Metro-compatible). Uses jimp-compact (transitive dep of Expo).
// Run: node artifacts/nino/scripts/split-earth-frames.js
const fs = require('fs');
const path = require('path');
const { createRequire } = require('module');

const root = path.resolve(__dirname, '..');
function loadJimp() {
  try { return require('jimp-compact'); } catch {}
  const pnpm = path.resolve(root, '../../node_modules/.pnpm');
  const dir = fs.readdirSync(pnpm).find((d) => d.startsWith('jimp-compact@'));
  if (!dir) throw new Error('jimp-compact not found');
  return createRequire(path.join(pnpm, dir, 'node_modules/jimp-compact/package.json'))('jimp-compact');
}
const Jimp = loadJimp();
const COLS = 9, ROWS = 8, FRAMES = 72, TILTS = 9, OUT = 128;

(async () => {
  const outDir = path.join(root, 'assets/earth/frames');
  fs.mkdirSync(outDir, { recursive: true });
  const lines = [];
  for (let t = 0; t < TILTS; t++) {
    const sheet = await Jimp.read(path.join(root, `assets/earth/globe_t${t}.jpg`));
    const cw = sheet.bitmap.width / COLS, ch = sheet.bitmap.height / ROWS;
    const row = [];
    for (let i = 0; i < FRAMES; i++) {
      const c = i % COLS, r = Math.floor(i / COLS);
      const name = `t${t}_${String(i).padStart(2, '0')}.jpg`;
      const f = sheet.clone().crop(Math.round(c * cw), Math.round(r * ch), Math.floor(cw), Math.floor(ch)).resize(OUT, OUT, Jimp.RESIZE_BILINEAR).quality(85);
      await f.writeAsync(path.join(outDir, name));
      row.push(`require('@/assets/earth/frames/${name}')`);
    }
    lines.push(`  [\n    ${row.join(',\n    ')},\n  ]`);
    console.log(`tilt ${t}: ${cw}x${ch} cells -> ${FRAMES} frames`);
  }
  const ts = `// AUTO-GENERATED by scripts/split-earth-frames.js — do not edit.\n// EARTH_FRAMES[tilt 0..8 (lat -60..60 step 15)][frame 0..71 (lon 0..355 step 5)]\n/* eslint-disable */\nexport const EARTH_FRAMES: number[][] = [\n${lines.join(',\n')},\n];\n`;
  fs.writeFileSync(path.join(root, 'components/earthFrames.ts'), ts);
})().catch((e) => { console.error(e); process.exit(1); });
